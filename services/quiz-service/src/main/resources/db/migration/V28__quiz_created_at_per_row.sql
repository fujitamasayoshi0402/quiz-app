-- DEV-244: クイズの作成時刻を、行を入れた時刻にする。
-- now() はトランザクションの開始時刻を返すため、一括取り込み（1 つのトランザクション）で入れたクイズは、すべて同じ時刻になっていた。
-- 登録順の出題は「レベル・並び順・作成時刻」で並べるので、時刻が重なると並びが決まらない（「まずは5問」の 1 問目が入れ替わった）。
-- clock_timestamp() は文ごとに今の時刻を返すため、取り込んだ順に時刻が増える。
-- 入っている行の時刻は変えない。順を直したいクイズは、消して流し直す（Runbook「prod のデモにパックを流す」）。
ALTER TABLE quiz.quizzes ALTER COLUMN created_at SET DEFAULT clock_timestamp();
